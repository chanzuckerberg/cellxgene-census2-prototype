"""Write `census2_sdk/obs_columns.py` from the store format's `OBS_COLUMNS`.

The SDK does not depend on the writer, so it holds a generated copy of the schema: one
typed attribute for each `obs` column, with the column class of its `ColType`, and
`MultiValueColumn` for the multi-valued columns of `catalog.MULTIVALUED`. A test
(`tests/test_obs_filter.py`) fails when the columns of the copy and of the store format
differ. The check compares the columns, not the text, so a change of ruff's format
does not fail it.

    python tools/generate_obs_columns.py            # write the module
    python tools/generate_obs_columns.py --check    # exit 1 when it is out of date
"""

import argparse
import pathlib
import sys

from census2_dataset_writer.store_format import OBS_COLUMNS, ColType

from census2_sdk.catalog import MULTIVALUED

TARGET = pathlib.Path(__file__).parents[1] / "src" / "census2_sdk" / "obs_columns.py"

CLASSES = {
    ColType.CATEGORY: "CategoryColumn",
    ColType.BOOL: "BoolColumn",
    ColType.STRING: "StringColumn",
    ColType.INT64: "IntColumn",
    ColType.FLOAT64: "FloatColumn",
}
# The kind of each column, as `obs_plan` checks a term against it.
KINDS = {
    ColType.CATEGORY: "category",
    ColType.BOOL: "bool",
    ColType.STRING: "string",
    ColType.INT64: "int",
    ColType.FLOAT64: "float",
}

HEADER = '''"""The `obs` columns of a Census 2 store, one typed attribute each.

Generated by `tools/generate_obs_columns.py` from
`census2_dataset_writer.store_format.OBS_COLUMNS`. Do not edit; run the tool again.
Both organisms share these columns.
"""

from census2_sdk.obs_filter import (
    BoolColumn,
    CategoryColumn,
    FloatColumn,
    IntColumn,
    MultiValueColumn,
    ObsNamespace,
    StringColumn,
)

# The kind of each column: category, multi, bool, string, int, or float.
KINDS: dict[str, str] = {
'''


def generate() -> str:
    lines = [HEADER]
    for name, col_type in OBS_COLUMNS:
        kind = "multi" if name in MULTIVALUED else KINDS[col_type]
        lines.append(f'    "{name}": "{kind}",\n')
    lines.append("}\n\n\n")
    lines.append("class Obs(ObsNamespace):\n")
    lines.append(
        '    """The `obs` columns of one organism: `census.homo_sapiens.obs`."""\n\n'
    )
    lines.append("    def __init__(self, organism: str) -> None:\n")
    lines.append("        super().__init__(organism)\n")
    for name, col_type in OBS_COLUMNS:
        cls = "MultiValueColumn" if name in MULTIVALUED else CLASSES[col_type]
        line = f'        self.{name} = {cls}("{name}", organism)\n'
        if len(line) > 89:  # the width of ruff format, and the newline
            line = f'        self.{name} = {cls}(\n            "{name}", organism\n        )\n'
        lines.append(line)
    return "".join(lines)


def expected() -> dict[str, tuple[str, str]]:
    """The class and the kind of each column, as the store format gives them."""
    out = {}
    for name, col_type in OBS_COLUMNS:
        multi = name in MULTIVALUED
        cls = "MultiValueColumn" if multi else CLASSES[col_type]
        out[name] = (cls, "multi" if multi else KINDS[col_type])
    return out


def current() -> dict[str, tuple[str, str]]:
    """The class and the kind of each column in the generated module."""
    from census2_sdk import obs_columns

    obs = obs_columns.Obs("homo_sapiens")
    return {
        name: (type(getattr(obs, name)).__name__, kind)
        for name, kind in obs_columns.KINDS.items()
    }


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--check", action="store_true", help="exit 1 when out of date")
    args = p.parse_args()
    text = generate()
    if args.check:
        if current() != expected():
            print(f"{TARGET} is out of date; run {sys.argv[0]}", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
